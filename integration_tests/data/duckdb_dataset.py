def create_source_table(connection: duckdb.DuckDBPyConnection, name: str = 'src',
                        generated: int = 2000) -> None:
    definitions = ', '.join(f'"{c}" {t}' for c, t in COLUMNS.items())
    connection.execute(f'CREATE TABLE {name} ({definitions})')
    for row in EDGE_ROWS:
        connection.execute(f'INSERT INTO {name} VALUES {row}')
    generated_rows = GENERATED.replace('{count}', str(generated))
    connection.execute(f'INSERT INTO {name} {generated_rows}')


def mismatches(
    connection: duckdb.DuckDBPyConnection,
    source: str,
    target: str,
    columns: List[str] = None,
    limit: int = 3,
    where: str = 'true',
) -> Dict[str, List]:
    """
    Columns whose values differ between two tables joined on id, with example rows.
    The target column is cast to the source type, so a different but equivalent type
    passes; a value that changed does not.
    """
    target_types = dict(connection.execute(
        'SELECT column_name, data_type FROM information_schema.columns WHERE table_name = ?',
        [target],
    ).fetchall())
    problems = {}
    for column in columns or COLUMN_NAMES:
        if column not in target_types:
            problems[column] = ['missing']
            continue
        source_type = COLUMNS[column]
        if source_type == 'JSON' or target_types[column] == 'JSON':
            left, right = f's."{column}"::JSON::VARCHAR', f't."{column}"::JSON::VARCHAR'
        else:
            # TRY_CAST: a value the source type cannot hold is reported, not raised.
            left, right = f's."{column}"', f'TRY_CAST(t."{column}" AS {source_type})'
            if source_type.startswith('TIMESTAMP_'):
                # DuckDB has no cast between timestamp precisions except through TIMESTAMP.
                right = (
                    f'COALESCE({right}, TRY_CAST(TRY_CAST(t."{column}" AS TIMESTAMP) '
                    f'AS {source_type}))'
                )
        rows = connection.execute(
            f'SELECT s.id, s."{column}"::VARCHAR, t."{column}"::VARCHAR '
            f'FROM (SELECT * FROM {source} WHERE {where}) s FULL JOIN {target} t ON s.id = t.id '
            f'WHERE {left} IS DISTINCT FROM {right} ORDER BY s.id LIMIT {limit}'
        ).fetchall()
        if rows:
            problems[column] = rows
    return problems
