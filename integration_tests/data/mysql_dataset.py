def create_source_table(cursor, name: str = 'src', generated: int = 2000) -> None:
    definitions = ', '.join(f'`{c}` {t}' for c, t in COLUMNS.items())
    cursor.execute(f'DROP TABLE IF EXISTS `{name}`')
    cursor.execute(f'CREATE TABLE `{name}` ({definitions})')
    cursor.execute("SET time_zone = '+00:00'")
    cursor.execute('SET SESSION cte_max_recursion_depth = 100000')
    for row in EDGE_ROWS:
        cursor.execute(f'INSERT INTO `{name}` VALUES {row}')
    cursor.execute(GENERATED.format(table=f'`{name}`', count=generated))


def rows(cursor, table: str, columns: List[str] = None) -> Dict[Any, Dict[str, Any]]:
    """Rows by their first column, as the driver returns them in a UTC session."""
    names = columns or COLUMN_NAMES
    cursor.execute("SET time_zone = '+00:00'")
    cursor.execute(
        f'SELECT {", ".join(f"`{c}`" for c in names)} FROM `{table}` ORDER BY 1',
    )
    return {row[0]: dict(zip(names, row)) for row in cursor.fetchall()}


def normalize(value: Any) -> Any:
    """One representation per value, so equal values in other types compare equal."""
    if isinstance(value, (bytes, bytearray)):
        return bytes(value)
    if isinstance(value, decimal.Decimal):
        return value.normalize() if value != 0 else decimal.Decimal(0)
    if isinstance(value, float):
        return decimal.Decimal(repr(value)).normalize() if value != 0 else decimal.Decimal(0)
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, (set, frozenset)):
        return ','.join(sorted(value))
    if isinstance(value, list):
        return ','.join(sorted(value))
    if isinstance(value, dt.datetime) and value.tzinfo is not None:
        return value.astimezone(dt.timezone.utc).replace(tzinfo=None)
    if isinstance(value, str) and value[:1] in '{[' and value[-1:] in '}]':
        try:
            return json.dumps(json.loads(value), sort_keys=True)
        except ValueError:
            return value
    return value


def mismatches(
    expected: Dict[Any, Dict[str, Any]],
    actual: Dict[Any, Dict[str, Any]],
    columns: List[str] = None,
    limit: int = 3,
) -> Dict[str, List]:
    """Columns whose values differ between two row maps, with example rows."""
    problems = {}
    if set(expected) != set(actual):
        problems['ids'] = sorted(set(expected) ^ set(actual))[:limit]
    for column in columns or COLUMN_NAMES:
        found = [
            (key, expected[key].get(column), actual[key].get(column))
            for key in sorted(set(expected) & set(actual), key=str)
            if normalize(expected[key].get(column)) != normalize(actual[key].get(column))
        ]
        if found:
            problems[column] = found[:limit]
    return problems
